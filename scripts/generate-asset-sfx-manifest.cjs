'use strict';

const fs = require('fs');
const path = require('path');

const frontendRoot = path.join(__dirname, '..', 'frontend');
const soundsRoot = path.join(frontendRoot, 'assets', 'sounds');
const outFile = path.join(frontendRoot, 'src', 'game', 'data', 'asset-sfx-manifest.js');

const AUDIO_EXT = new Set(['.wav', '.ogg', '.m4a', '.mp3', '.flac', '.aac']);

function walk(dir) {
  const out = [];
  for (const name of fs.readdirSync(dir)) {
    const p = path.join(dir, name);
    const st = fs.statSync(p);
    if (st.isDirectory()) {
      out.push(...walk(p));
    } else if (AUDIO_EXT.has(path.extname(name).toLowerCase())) {
      const rel = path.relative(soundsRoot, p).replace(/\\/g, '/');
      const short = path.basename(rel);
      const folder = path.dirname(rel);
      const label =
        folder && folder !== '.'
          ? `${folder.replace(/\//g, ' › ')} › ${short}`
          : short;
      out.push({ label, relPath: rel });
    }
  }
  return out;
}

function main() {
  if (!fs.existsSync(soundsRoot)) {
    console.error('Missing sounds folder:', soundsRoot);
    process.exit(1);
  }
  const tracks = walk(soundsRoot).sort((a, b) => a.relPath.localeCompare(b.relPath));
  const header =
    '// AUTO-GENERATED by: npm run generate:asset-sfx-manifest (apps/shooter-game). Do not edit by hand.\n';
  const body = `(function (g) {
  g.ASSET_SFX_TRACKS = ${JSON.stringify(tracks, null, 2)};
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, header + body, 'utf8');
  console.log(`Wrote ${tracks.length} tracks -> ${outFile}`);
}

main();
